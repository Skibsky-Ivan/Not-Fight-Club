export function getRandomEndPhrase(
  robberId: string,
  location: LocationType,
  outcome: BattleOutcomeType,
): string {
  const roguePhrases = BATTLE_END_PHRASES[robberId];
  if (
    !roguePhrases ||
    !roguePhrases[location] ||
    !roguePhrases[location][outcome]
  ) {
    return 'Поединок завершён!';
  }

  const list = roguePhrases[location][outcome];
  const randomIndex = Math.floor(Math.random() * list.length);
  return list[randomIndex];
}
