export function getRandomStartPhrase(
  robberId: string,
  location: LocationType,
): string {
  const roguePhrases = BATTLE_START_PHRASES[robberId];
  if (!roguePhrases || !roguePhrases[location]) {
    return 'Противник готовится к бою!';
  }

  const list = roguePhrases[location];
  const randomIndex = Math.floor(Math.random() * list.length);
  return list[randomIndex];
}
