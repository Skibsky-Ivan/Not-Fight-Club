export function getRandomRogueTaunt(rogueId: string): string {
  const rogue = ROGUE_TAUNTS[rogueId];

  if (!rogue || !rogue.length) {
    return 'Этот разбойник отказывается идти с тобой!';
  }

  const randomIndex = Math.floor(Math.random() * rogue.length);
  return rogue[randomIndex];
}
